import { createActionGroup, emptyProps, props } from '@ngrx/store';
import {
    Land,
    LandMitOrtUndSchuleAnlegenRequest,
    Ort,
    OrtMitSchuleAnlegenRequest,
    Schule,
    SchuleAnlegenOderAendernRequest,
    SchulkatalogAdminKontext,
    Schulkuerzel,
} from '../../model/schulkatalog.model';

export const schulkatalogActions = createActionGroup({
    source: 'MKAdmin Schulkatalog',
    events: {
        loadLaender: emptyProps(),
        loadLaenderSucceeded: props<{ laender: Land[] }>(),
        landSelected: props<{ land: Land }>(),
        loadOrte: props<{ land: Land }>(),
        loadOrteSucceeded: props<{ orte: Ort[] }>(),
        backToLaenderRequested: emptyProps(),
        ortSelected: props<{ ort: Ort }>(),
        loadSchulen: props<{ ort: Ort }>(),
        loadSchulenSucceeded: props<{ schulen: Schule[] }>(),
        backToOrteRequested: emptyProps(),
        landMitOrtUndSchuleAnlegenSelected: emptyProps(),
        landMitOrtUndSchuleAnlegen: props<{ payload: LandMitOrtUndSchuleAnlegenRequest }>(),
        landMitOrtUndSchuleAnlegenSucceeded: props<{ schulkuerzel: Schulkuerzel }>(),
        ortMitSchuleAnlegenSelected: emptyProps(),
        ortMitSchuleAnlegen: props<{ land: Land; payload: OrtMitSchuleAnlegenRequest }>(),
        ortMitSchuleAnlegenSucceeded: props<{ land: Land; schulkuerzel: Schulkuerzel }>(),
        schuleAnlegenSelected: emptyProps(),
        schuleAnlegen: props<{ ort: Ort; payload: SchuleAnlegenOderAendernRequest }>(),
        schuleAnlegenSucceeded: props<{ ort: Ort; schulkuerzel: Schulkuerzel }>(),
        schuleUmbenennenSelected: props<{ schule: Schule }>(),
        schuleUmbenennen: props<{ schule: Schule; payload: SchuleAnlegenOderAendernRequest }>(),
        schuleUmbenennenSucceeded: props<{ schule: Schule; schulkuerzel: Schulkuerzel }>(),
        loadActionFailed: props<{ kontext: SchulkatalogAdminKontext; error: Error }>(),
        changeActionFailed: props<{ error: Error }>(),
        resetSchulkatalog: emptyProps(),
    },
});
